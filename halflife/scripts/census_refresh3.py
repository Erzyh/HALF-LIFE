"""Census refresh of 2026-10-12 (third pass): complete the retirement vocabulary under a stated completeness rule.

python scripts/census_refresh3.py

What it does, idempotently:
1. target_models.json gains the identifiers listed in data/census_add_models_2026-10-12.json (36 on 2026-10-12: the remaining
   language-model identifiers with a published retirement date on the three vendor pages as read on 2026-10-11), records the
   completeness rule and an audit entry, and gains a "release" date for EVERY identifier (the date embedded in the identifier,
   else the announcement date from scripts/lifecycle_figure.py, else the add-list), so that the survival analysis can start a
   paper's time at risk no earlier than the release of the identifier that retires first. The previous file is archived as
   data/target_models_2026-10-12-pre.json.
2. Works naming a new identifier are read from data/census_add_raw_2026-10-12.jsonl (scripts/census_harvest.py) and folded into
   data/census_v2.csv (archived first as data/census_v2_2026-10-12-pre.csv) after the filters of the original build: a persistent
   identifier (DOI or arXiv), a publication year not before the release of every resolved identifier, and no duplicate title.
   Works already in the census get the new identifiers appended; statuses are recomputed.
3. Dateless aliases are resolved at fold-in: gpt-5 / gpt-5-mini / gpt-5-nano count only for papers dated on or after the
   2025-08-07 launch that name no later gpt-5.x identifier (checked against the extension harvest data/census_ext_raw.jsonl,
   which searched every gpt-5.x phrase), claude-opus-4 / claude-sonnet-4 / claude-opus-4-1 only for papers dated on or after the
   launch that name no later Claude 4.x identifier; claude-instant and claude-instant-1 resolve to the Instant family
   (every version retired 2024-11-06); gpt-4-turbo-preview to the 2026-03-26 retirement of both previews. A bare alias is
   dropped when the paper also names a dated snapshot of the same family (the snapshot decides).
4. Writes data/census_refresh3_summary.json. Downstream tables and figures are regenerated by their own scripts. No API calls.
"""
import json
import re
import shutil
import sys
from collections import Counter
from datetime import date
from pathlib import Path

import pandas as pd

HALF = Path(__file__).resolve().parents[1]
DATA = HALF / "data"
sys.path.insert(0, str(HALF / "scripts"))
from lifecycle_figure import RELEASE as LIFECYCLE_RELEASE, embedded_date  # noqa: E402

ADD = json.load(open(DATA / "census_add_models_2026-10-12.json", encoding="utf-8"))
NEW = ADD["models"]
RELEASE_OF = {m["id"]: date.fromisoformat(m["release"]) for m in NEW}

LATER_GPT5 = {"gpt-5.1", "gpt-5.1-2025-11-13", "gpt-5.2", "gpt-5.2-2025-12-11", "gpt-5.2-pro", "gpt-5.2-pro-2025-12-11", "gpt-5.4", "gpt-5.4-2026-03-05",
              "gpt-5.4-mini", "gpt-5.4-mini-2026-03-17", "gpt-5.4-nano", "gpt-5.4-nano-2026-03-17", "gpt-5.4-pro", "gpt-5.4-pro-2026-03-05",
              "gpt-5.5", "gpt-5.5-2026-04-23", "gpt-5.5-pro", "gpt-5.5-pro-2026-04-23", "gpt-5.6-sol", "gpt-5.6-terra", "gpt-5.6-luna"}
GPT5_DATED = {"gpt-5-2025-08-07", "gpt-5-mini-2025-08-07", "gpt-5-nano-2025-08-07", "gpt-5-pro", "gpt-5-pro-2025-10-06"}
LATER_OPUS4 = {"claude-opus-4-5", "claude-opus-4-5-20251101", "claude-opus-4-6", "claude-opus-4-7", "claude-opus-4-8"}
LATER_SONNET4 = {"claude-sonnet-4-5", "claude-sonnet-4-5-20250929", "claude-sonnet-4-6"}
# alias -> (launch date, identifiers whose presence means the bare phrase came from them or supersedes them)
ALIAS_RULES = {
    "gpt-5": (date(2025, 8, 7), GPT5_DATED | LATER_GPT5),
    "gpt-5-mini": (date(2025, 8, 7), GPT5_DATED | LATER_GPT5),
    "gpt-5-nano": (date(2025, 8, 7), GPT5_DATED | LATER_GPT5),
    "claude-opus-4": (date(2025, 5, 22), {"claude-opus-4-20250514", "claude-opus-4-1", "claude-opus-4-1-20250805"} | LATER_OPUS4),
    "claude-sonnet-4": (date(2025, 5, 22), {"claude-sonnet-4-20250514"} | LATER_SONNET4),
    "claude-opus-4-1": (date(2025, 8, 5), {"claude-opus-4-1-20250805"}),
    "claude-instant": (date(2023, 3, 14), {"claude-instant-1", "claude-instant-1.0", "claude-instant-1.1", "claude-instant-1.2"}),
    "claude-instant-1": (date(2023, 3, 14), {"claude-instant-1.0", "claude-instant-1.1", "claude-instant-1.2"}),
    "gpt-4-turbo-preview": (date(2023, 11, 6), {"gpt-4-1106-preview", "gpt-4-0125-preview"}),
    "gemini-pro-vision": (date(2023, 12, 13), {"gemini-1.0-pro-vision"}),
}


def norm_title(t):
    return re.sub(r"[^a-z0-9]+", " ", str(t).lower()).strip()


def parse_date(s):
    m = re.match(r"(\d{4})(?:-(\d{2}))?(?:-(\d{2}))?", str(s))
    if not m:
        return None
    return date(int(m.group(1)), int(m.group(2) or 7), int(m.group(3) or 1))


def release_for(mid):
    """Release date of an identifier: embedded in the id, else the announcement table, else the add-list."""
    if mid in RELEASE_OF:
        return RELEASE_OF[mid]
    d = embedded_date(mid)
    if d is not None:
        return d
    if mid in LIFECYCLE_RELEASE:
        return date.fromisoformat(LIFECYCLE_RELEASE[mid])
    return None


def resolve(new_ids, models_all, ext_names, pub, counters):
    """Which of a work's NEW identifiers place it in the census, with the release date each resolves to."""
    out = {}
    for m in new_ids:
        rule = ALIAS_RULES.get(m)
        if rule:
            launch, superseders = rule
            if pub < launch:
                counters[f"{m}: paper dated before the launch, dropped"] += 1
                continue
            if (models_all | ext_names) & superseders:
                counters[f"{m}: a dated or later identifier of the family is named, bare alias dropped"] += 1
                continue
            counters[f"{m}: resolved"] += 1
        out[m] = RELEASE_OF[m]
    return out


def main():
    tm_path = HALF / "target_models.json"
    tm = json.load(open(tm_path, encoding="utf-8"))
    arch = DATA / "target_models_2026-10-12-pre.json"
    if not arch.exists():
        shutil.copy(tm_path, arch)
    have = {m["id"]: m for m in tm["models"]}
    added = []
    for m in NEW:
        if m["id"] in have:
            continue
        entry = {k: v for k, v in m.items() if k not in ("release_note",)}
        tm["models"].append(entry)
        added.append(m["id"])
    missing_release = []
    for m in tm["models"]:
        if not m.get("release"):
            r = release_for(m["id"])
            if r is None:
                missing_release.append(m["id"])
            else:
                m["release"] = r.isoformat()
    tm["completeness_rule"] = ADD["completeness_rule"]
    tm["updated"] = tm["updated"].split("; 2026-10-12")[0] + ("; 2026-10-12 third refresh: the vocabulary completed under the stated completeness rule "
                                                            f"({len(added)} identifiers added; previous file data/target_models_2026-10-12-pre.json); "
                                                            "every identifier now carries a release date")
    tm.setdefault("audit", {})["2026-10-12 refresh"] = ("scripts/census_refresh3.py: the three vendor pages as read on 2026-10-11 were re-read against the "
                                                        "completeness rule recorded in 'completeness_rule'; the remaining language-model identifiers with a "
                                                        f"published retirement date were harvested on 2026-10-12 and folded in ({', '.join(added)}). Excluded by "
                                                        "the rule: ambiguous phrases (ada, babbage, curie, davinci, babbage-002, davinci-002, gemini-pro), non-text "
                                                        "modalities, the specialized tool products under OpenAI's three-month notice policy and Gemini computer-use, "
                                                        "fine-tuning names, and the Gemini 2.5 / 3.6 / 3.7 models whose Vertex dates the Gemini API page contradicts.")
    json.dump(tm, open(tm_path, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print(f"target_models.json: {len(added)} identifiers added -> {len(tm['models'])} in total; release dates missing for {missing_release}")

    base_path = DATA / "census_v2.csv"
    arch_c = DATA / "census_v2_2026-10-12-pre.csv"
    if not arch_c.exists():
        shutil.copy(base_path, arch_c)
    base = pd.read_csv(arch_c, low_memory=False)
    status_of = {m["id"]: m["status"] for m in tm["models"]}
    vocab = set(status_of)
    new_ids = {m["id"] for m in NEW}
    titles = {norm_title(t) for t in base.title}

    # names each work carries in the extension harvest (every gpt-5.x and Claude 4.x phrase was searched there)
    ext_names = {}
    ext_raw = DATA / "census_ext_raw.jsonl"
    if ext_raw.exists():
        for line in open(ext_raw, encoding="utf-8"):
            if line.strip():
                r = json.loads(line)
                ext_names.setdefault(r["openalex_id"], set()).add(r["matched_model"])
    else:
        print("note: data/census_ext_raw.jsonl is absent (it is in the Zenodo deposit); later-identifier checks use the census file only")

    by_id = {}
    n_rec = 0
    raw = DATA / "census_add_raw_2026-10-12.jsonl"
    for line in open(raw, encoding="utf-8"):
        if not line.strip():
            continue
        r = json.loads(line)
        n_rec += 1
        e = by_id.setdefault(r["openalex_id"], {**r, "matched": set()})
        e["matched"].add(r["matched_model"])
    counters, filt = Counter(), Counter()
    base_ids = dict(zip(base.openalex_id, base.index))
    added_rows, union_updates = [], 0
    per_source_added = Counter()
    for oid, e in by_id.items():
        pub = parse_date(e.get("date")) or (date(int(e["year"]), 7, 1) if e.get("year") else None)
        if pub is None:
            filt["no date"] += 1
            continue
        models_all = set(e["matched"])
        if oid in base_ids:
            models_all |= {m for m in str(base.at[base_ids[oid], "matched_models"]).split("|") if m}
        q = resolve(models_all & new_ids, models_all, ext_names.get(oid, set()), pub, counters)
        q = {m: rel for m, rel in q.items() if m in vocab}
        if not q:
            continue
        if oid in base_ids:
            i = base_ids[oid]
            cur = [m for m in str(base.at[i, "matched_models"]).split("|") if m]
            new = sorted(set(cur) | set(q))
            if new != sorted(cur):
                base.at[i, "matched_models"] = "|".join(new); union_updates += 1
            continue
        doi = str(e.get("doi") or ""); oa = str(e.get("oa_url") or "")
        if doi.startswith("https://doi.org/"):
            pid = "doi"
        elif "arxiv.org" in oa:
            pid = "arxiv"
        else:
            filt["no persistent identifier"] += 1; continue
        if all(pub.year < rel.year for rel in q.values()):
            filt["publication year before the release of every named identifier"] += 1; continue
        nt = norm_title(e.get("title"))
        if nt in titles:
            filt["duplicate title"] += 1; continue
        titles.add(nt)
        for m in q:
            per_source_added[m] += 1
        added_rows.append({"matched_models": "|".join(sorted(q)), "statuses": "", "citations": e.get("citations"), "year": e.get("year"), "date": e.get("date"),
                           "type": e.get("type"), "field": e.get("field"), "topic": e.get("topic"), "language": e.get("language"), "is_oa": e.get("is_oa"),
                           "venue": e.get("venue"), "title": e.get("title"), "doi": doi if pid == "doi" else None, "oa_url": oa, "openalex_id": oid,
                           "pid_type": pid, "pid_type.1": pid})
    new = pd.concat([base, pd.DataFrame(added_rows, columns=base.columns)], ignore_index=True)
    new["statuses"] = new.matched_models.map(lambda s: "|".join(sorted({status_of.get(m, "?") for m in str(s).split("|") if m})))
    new.to_csv(base_path, index=False, encoding="utf-8-sig")
    per_id = Counter(m for s in new.matched_models for m in str(s).split("|"))
    summary = {"refresh_date": "2026-10-12", "identifiers_added": added, "identifiers_total": len(tm["models"]),
               "vendor_counts": dict(Counter(m["vendor"] for m in tm["models"])), "records_read": n_rec, "unique_works_considered": len(by_id),
               "papers_before": int(len(base)), "papers_added": len(added_rows), "papers_after": int(len(new)), "base_papers_with_new_identifiers": union_updates,
               "filters_on_additions": dict(filt), "alias_resolution": dict(counters), "added_papers_by_matched_identifier": dict(per_source_added),
               "statuses_after": new.statuses.value_counts().to_dict(), "papers_per_added_identifier": {m: per_id.get(m, 0) for m in new_ids},
               "release_dates_missing": missing_release}
    json.dump(summary, open(DATA / "census_refresh3_summary.json", "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print(json.dumps({k: v for k, v in summary.items() if k != "identifiers_added"}, ensure_ascii=False, indent=1)[:3500])


if __name__ == "__main__":
    main()
