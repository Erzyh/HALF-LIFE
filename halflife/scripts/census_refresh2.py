"""Census refresh of 2026-10-11 (second pass): fold in the identifiers with published retirement dates that the vocabulary
of 2 September and the refresh of 2 October did not track.

python scripts/census_refresh2.py

What it does, idempotently:
1. target_models.json gains six identifiers (the previous file is archived as data/target_models_2026-10-11-pre.json):
   gpt-3.5-turbo-instruct and gpt-3.5-turbo-1106 (retired 2026-09-28, announced 2025-09-26, on the vendor page in every
   snapshot since; harvested on 2026-10-11 into data/census_add_raw_2026-10-11.jsonl with scripts/census_harvest.py
   --models data/census_add_models_2026-10-11.json; babbage-002 and davinci-002, harvested in the same run, are NOT folded
   in because the phrase search cannot separate them from text-davinci-002 and text-babbage-001: 827 of the 1,098 works it
   returned that were already in the census name text-davinci-002), and gpt-5.1, gpt-5.1-2025-11-13, gpt-5.4-nano
   and gpt-5.4-nano-2026-03-17 (retirement 2027-04-01 announced 2026-10-01, missed by the refresh of 2 October; their works
   are already in the extension harvest data/census_ext_raw.jsonl).
2. The dateless alias gpt-3.5-turbo resolves to gpt-3.5-turbo-1106 for papers dated 2023-12-11 to 2024-02-15, the window the
   2 October refresh dropped as unresolved because it had not found the 1106 retirement date; scripts/census_survival.py and
   scripts/census_extension.py apply the same rule. Papers already in the census with the alias in that window need no change
   in the file: the survival build resolves them.
3. Works naming a new identifier, or the alias in that window, are added to data/census_v2.csv (archived first as
   data/census_v2_2026-10-11-pre.csv) after the three filters of the original build: a persistent identifier (DOI or arXiv),
   a publication year not before the release of every resolved identifier, and no duplicate title. Works already in the census
   get the new identifiers appended; statuses are recomputed.
4. Writes data/census_refresh2_summary.json. Downstream tables and figures are regenerated by their own scripts
   (scripts/check_regeneration.py and the hand-run figure scripts). No API calls.
"""
import json
import re
import shutil
from collections import Counter
from datetime import date
from pathlib import Path

import pandas as pd

HALF = Path(__file__).resolve().parents[1]
DATA = HALF / "data"
GPT35_1106, GPT35_0125, GPT4O_MOVED = date(2023, 12, 11), date(2024, 2, 16), date(2024, 10, 2)
ANNOUNCED = "2026-10-01"

NEW = [
    {"id": "gpt-3.5-turbo-instruct", "vendor": "openai", "status": "dead", "shutdown": "2026-09-28", "priority": 3, "release": "2023-09-21",
     "note": "added 2026-10-11: completion model, retirement announced 2025-09-26; missing from the 2026-09-02 vocabulary"},
    {"id": "gpt-3.5-turbo-1106", "vendor": "openai", "status": "dead", "shutdown": "2026-09-28", "priority": 3, "release": "2023-11-06",
     "note": "added 2026-10-11: chat snapshot, retirement announced 2025-09-26; the dateless alias gpt-3.5-turbo resolves to it from 2023-12-11 to 2024-02-15"},
    {"id": "gpt-5.1-2025-11-13", "vendor": "openai", "status": "dying", "shutdown": "2027-04-01", "priority": 3, "release": "2025-11-13",
     "note": "added 2026-10-11: retirement announced 2026-10-01 (missed by the refresh of 2 October); replacement gpt-6-sol"},
    {"id": "gpt-5.1", "vendor": "openai", "status": "dying", "shutdown": "2027-04-01", "priority": 3, "alias": "gpt-5.1-2025-11-13", "release": "2025-11-13",
     "note": "added 2026-10-11: dateless alias of gpt-5.1-2025-11-13"},
    {"id": "gpt-5.4-nano-2026-03-17", "vendor": "openai", "status": "dying", "shutdown": "2027-04-01", "priority": 3, "release": "2026-03-17",
     "note": "added 2026-10-11: retirement announced 2026-10-01; replacement gpt-6-luna"},
    {"id": "gpt-5.4-nano", "vendor": "openai", "status": "dying", "shutdown": "2027-04-01", "priority": 3, "alias": "gpt-5.4-nano-2026-03-17", "release": "2026-03-17",
     "note": "added 2026-10-11: dateless alias of gpt-5.4-nano-2026-03-17"},
]
RELEASE_OF = {m["id"]: date.fromisoformat(m["release"]) for m in NEW}
RELEASE_OF.update({"gpt-3.5-turbo-0613": date(2023, 6, 13), "gpt-3.5-turbo-0125": date(2024, 1, 25), "gpt-4o-2024-05-13": date(2024, 5, 13)})
FROM_EXT = {"gpt-5.1", "gpt-5.1-2025-11-13", "gpt-5.4-nano", "gpt-5.4-nano-2026-03-17", "gpt-3.5-turbo"}


def norm_title(t):
    return re.sub(r"[^a-z0-9]+", " ", str(t).lower()).strip()


def parse_date(s):
    m = re.match(r"(\d{4})(?:-(\d{2}))?(?:-(\d{2}))?", str(s))
    if not m:
        return None
    return date(int(m.group(1)), int(m.group(2) or 7), int(m.group(3) or 1))


def resolve(models, pub, counters):
    """Identifiers of one work that place it in the retired-or-retiring census, with the release date each resolves to."""
    out = {}
    for m in models:
        if m == "gpt-3.5-turbo":
            if any(x.startswith("gpt-3.5-turbo-") for x in models):
                continue
            if pub < GPT35_1106:
                out[m] = RELEASE_OF["gpt-3.5-turbo-0613"]; counters["gpt-3.5-turbo -> 0613"] += 1
            elif pub < GPT35_0125:
                out[m] = RELEASE_OF["gpt-3.5-turbo-1106"]; counters["gpt-3.5-turbo -> 1106 (window dropped on 2 October, now resolved)"] += 1
            else:
                out[m] = RELEASE_OF["gpt-3.5-turbo-0125"]; counters["gpt-3.5-turbo -> 0125"] += 1
        elif m == "gpt-4o":
            if any(x.startswith("gpt-4o-2024-") for x in models):
                continue
            if pub < GPT4O_MOVED:
                out[m] = RELEASE_OF["gpt-4o-2024-05-13"]; counters["gpt-4o -> 2024-05-13"] += 1
            else:
                counters["gpt-4o -> still-served snapshot, outside the census"] += 1
        elif m in RELEASE_OF:
            out[m] = RELEASE_OF[m]
    return out


def main():
    tm_path = HALF / "target_models.json"
    tm = json.load(open(tm_path, encoding="utf-8"))
    arch = DATA / "target_models_2026-10-11-pre.json"
    if not arch.exists():
        shutil.copy(tm_path, arch)
    have = {m["id"] for m in tm["models"]}
    added = [m for m in NEW if m["id"] not in have]
    for m in added:
        tm["models"].append({k: v for k, v in m.items() if k != "release"})
    tm["updated"] = tm["updated"].split("; 2026-10-11")[0] + ("; 2026-10-11 second refresh: six identifiers with published retirement dates that the earlier passes "
                                                            "did not track (previous file data/target_models_2026-10-11-pre.json)")
    tm.setdefault("audit", {})["2026-10-11 refresh"] = ("scripts/census_refresh2.py: gpt-3.5-turbo-instruct and gpt-3.5-turbo-1106 (retired 2026-09-28, announced 2025-09-26) "
                                                        "harvested on 2026-10-11 (babbage-002 and davinci-002, harvested in the same run, are not tracked: the phrase search "
                                                        "cannot separate them from text-davinci-002 and text-babbage-001); gpt-5.1, gpt-5.1-2025-11-13, gpt-5.4-nano, gpt-5.4-nano-2026-03-17 "
                                                        "(retirement 2027-04-01, announced 2026-10-01) folded in from the extension harvest; the gpt-3.5-turbo alias now resolves "
                                                        "to gpt-3.5-turbo-1106 between 2023-12-11 and 2024-02-15. Not tracked, by scope: the specialized variants the OpenAI page "
                                                        "lists under its three-month notice policy (codex, chat-latest, deep-research, search and computer-use previews) and the "
                                                        "audio, image, video, embedding and moderation models.")
    json.dump(tm, open(tm_path, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print(f"target_models.json: {len(added)} identifiers added -> {len(tm['models'])} in total")

    base_path = DATA / "census_v2.csv"
    arch_c = DATA / "census_v2_2026-10-11-pre.csv"
    if not arch_c.exists():
        shutil.copy(base_path, arch_c)
    base = pd.read_csv(arch_c, low_memory=False)
    status_of = {m["id"]: m["status"] for m in tm["models"]}
    vocab = set(status_of)
    titles = {norm_title(t) for t in base.title}
    by_id = {}
    n_rec = Counter()
    sources = [("add", DATA / "census_add_raw_2026-10-11.jsonl", None), ("ext", DATA / "census_ext_raw.jsonl", FROM_EXT)]
    for name, path, keep in sources:
        if not path.exists():
            print(f"missing {path}")
            continue
        for line in open(path, encoding="utf-8"):
            if not line.strip():
                continue
            r = json.loads(line)
            if keep is not None and r["matched_model"] not in keep:
                continue
            n_rec[name] += 1
            e = by_id.setdefault(r["openalex_id"], {**r, "matched": set()})
            e["matched"].add(r["matched_model"])
    counters, filt = Counter(), Counter()
    base_ids = dict(zip(base.openalex_id, base.index))
    added_rows, union_updates = [], 0
    per_source_added = Counter()
    for oid, e in by_id.items():
        pub = parse_date(e.get("date")) or (date(int(e["year"]), 7, 1) if e.get("year") else None)
        if pub is None:
            filt["no date"] += 1
            continue
        models_all = set(e["matched"])
        if oid in base_ids:
            models_all |= set(str(base.at[base_ids[oid], "matched_models"]).split("|"))
        q = resolve(models_all, pub, counters)
        q = {m: rel for m, rel in q.items() if m in vocab}
        if not q:
            continue
        if oid in base_ids:
            i = base_ids[oid]
            cur = [m for m in str(base.at[i, "matched_models"]).split("|") if m]
            new = sorted(set(cur) | set(q))
            if new != sorted(cur):
                base.at[i, "matched_models"] = "|".join(new); union_updates += 1
            continue
        doi = str(e.get("doi") or ""); oa = str(e.get("oa_url") or "")
        if doi.startswith("https://doi.org/"):
            pid = "doi"
        elif "arxiv.org" in oa:
            pid = "arxiv"
        else:
            filt["no persistent identifier"] += 1; continue
        if all(pub.year < rel.year for rel in q.values()):
            filt["publication year before the release of every named identifier"] += 1; continue
        nt = norm_title(e.get("title"))
        if nt in titles:
            filt["duplicate title"] += 1; continue
        titles.add(nt)
        for m in e["matched"]:
            per_source_added[m] += 1
        added_rows.append({"matched_models": "|".join(sorted(q)), "statuses": "", "citations": e.get("citations"), "year": e.get("year"), "date": e.get("date"),
                           "type": e.get("type"), "field": e.get("field"), "topic": e.get("topic"), "language": e.get("language"), "is_oa": e.get("is_oa"),
                           "venue": e.get("venue"), "title": e.get("title"), "doi": doi if pid == "doi" else None, "oa_url": oa, "openalex_id": oid,
                           "pid_type": pid, "pid_type.1": pid})
    new = pd.concat([base, pd.DataFrame(added_rows, columns=base.columns)], ignore_index=True)
    new["statuses"] = new.matched_models.map(lambda s: "|".join(sorted({status_of.get(m, "?") for m in str(s).split("|") if m})))
    new.to_csv(base_path, index=False, encoding="utf-8-sig")
    per_id = Counter(m for s in new.matched_models for m in str(s).split("|"))
    summary = {"refresh_date": "2026-10-11", "identifiers_added": [m["id"] for m in NEW], "identifiers_total": len(tm["models"]),
               "vendor_counts": dict(Counter(m["vendor"] for m in tm["models"])), "records_read": dict(n_rec), "unique_works_considered": len(by_id),
               "papers_before": int(len(base)), "papers_added": len(added_rows), "papers_after": int(len(new)), "base_papers_with_new_identifiers": union_updates,
               "filters_on_additions": dict(filt), "alias_resolution": dict(counters), "added_papers_by_matched_identifier": dict(per_source_added),
               "statuses_after": new.statuses.value_counts().to_dict(), "papers_per_added_identifier": {m["id"]: per_id.get(m["id"], 0) for m in NEW}}
    json.dump(summary, open(DATA / "census_refresh2_summary.json", "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print(json.dumps({k: v for k, v in summary.items() if k != "identifiers_added"}, ensure_ascii=False, indent=1)[:3000])


if __name__ == "__main__":
    main()
